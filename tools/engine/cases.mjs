// Top 8 muscles per SPEC §4 case and sex, and engine timings. Loads the TS engine through Vite's SSR loader (no new deps).
// Usage: node tools/engine/cases.mjs [--time]    (cases to stdout; --time prints timing lines)
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';

const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const L = (p) => vite.ssrLoadModule(p);
const [{ protoToPose }, { effort, effortOverMove, engineData }, { setupVariant, supportPin }, { explain }, { generateTask }] =
  await Promise.all([L('/src/library/exercises.ts'), L('/src/engine/effort.ts'), L('/src/engine/setup.ts'), L('/src/engine/explain.ts'), L('/src/library/taskgen.ts')]);

const read = (f) => JSON.parse(readFileSync(`public/data/${f}`, 'utf8'));
const data = engineData({ rig: read('body/rig.json'), manifest: read('body/manifest.json'), segments: read('segments.json'), strengths: read('strengths.json'), actions: read('actions.json') });
const tables = { loads: read('loads.json'), supports: read('supports.json') };
const recs = read('exercises.json').exercises; // v2 flat records; tasks come from taskgen (tasks.json is gone)
const tb = read('taskbuilder.json');
const scale = (sex) => { const k = data.skel[sex]; return k.H[k.names.indexOf('pelvis')][1] / 0.965; };

// exercise record -> { keyframes, supports per keyframe, loads } for one sex
function rec(id, kg, sex) {
  const r = recs.find((x) => x.id === id), s = scale(sex);
  const setups = r.keyframes.map((k) => setupVariant(r.id, r.props, supportPin(k), tables, { ...r.loads, ...kg }));
  return { r, keyframes: r.keyframes.map((k) => protoToPose(k, s)), loads: setups[0].loads, supports: setups.map((x) => x.supports) };
}
const task = (st, sex) => { const g = generateTask(st, data, sex, tables, tb); if ('disabled' in g) throw new Error(g.disabled); return g; };
const merge = (rs) => {
  const ids = new Set(rs.flatMap((r) => Object.keys(r.muscle)));
  return { ...rs[0], lowerBack: rs.reduce((x, r) => (r.lowerBack.momentNm > x.momentNm ? r.lowerBack : x), rs[0].lowerBack),
    muscle: Object.fromEntries([...ids].map((id) => [id, rs.reduce((x, r) => ((r.muscle[id]?.level ?? 0) > x.level ? r.muscle[id] : x), rs[0].muscle[id]) ])) };
};
/** peak over the keyframe pairs (each with its own supports), closing the loop for tasks */
function over({ keyframes, loads, supports }, sex, loop = false) {
  const n = keyframes.length, rs = [];
  for (let i = 0; i < (loop ? n : n - 1); i++) rs.push(effortOverMove(keyframes[i], keyframes[(i + 1) % n], { sex, loads, supports: supports[i] }, data));
  return merge(rs);
}
const at = (v, k, sex) => effort({ pose: v.keyframes[k], poseB: v.keyframes[Math.min(k + 1, v.keyframes.length - 1)], sex, loads: v.loads, supports: v.supports[k] }, data);
const lean = (v) => ({ ...v, keyframes: v.keyframes.map((k) => ({ ...k, root: { ...k.root, pitch: -10 } })) });
const PARTS = new Map(data.parts.map((p) => [p.id, p]));

function top(r) {
  const rows = Object.entries(r.muscle).filter(([, m]) => m.role !== 'none' && m.level > 0)
    .sort((x, y) => y[1].level - x[1].level || ['work', 'help', 'hold'].indexOf(x[1].role) - ['work', 'help', 'hold'].indexOf(y[1].role)).slice(0, 8);
  return rows.map(([id, m]) => { const p = PARTS.get(+id); return `- ${p.plain} (${p.side}) ${m.level.toFixed(2)} ${m.role} — ${m.reasons[0] ? explain(m.reasons[0], p.side) : ''}`; });
}
const head = (r) => `lowerBack ${r.lowerBack.momentNm.toFixed(1)} Nm (level ${r.lowerBack.level.toFixed(2)}); balance margin ${r.balance.margin.toFixed(3)} m${r.balance.comOverFeet ? '' : ' — The centre of mass is beyond the feet in this pose'}`;

if (process.argv.includes('--time')) {
  const med = (xs) => xs.sort((p, q) => p - q)[xs.length >> 1];
  for (const sex of ['male', 'female'])
    for (const [id, kg] of [['barbell-curl', {}], ['back-squat', {}], ['pull-up', {}]]) {
      const v = rec(id, kg, sex), a = v.keyframes[0], b = v.keyframes[1], input = { sex, loads: v.loads, supports: v.supports[0] };
      for (let i = 0; i < 20; i++) { effort({ ...input, pose: a, poseB: b }, data); effortOverMove(a, b, input, data); } // warm-up
      const t1 = [], t9 = [];
      for (let i = 0; i < 200; i++) {
        let t = performance.now(); effort({ ...input, pose: a, poseB: b }, data); t1.push(performance.now() - t);
        t = performance.now(); effortOverMove(a, b, input, data); t9.push(performance.now() - t);
      }
      console.log(`${sex} ${id}: effort ${med(t1).toFixed(2)} ms, effortOverMove(9) ${med(t9).toFixed(2)} ms`);
    }
} else {
  const out = ['# Cases: top 8 muscles per case and sex', '', 'Generated by tools/engine/cases.mjs. Levels 0..1; peak over the keyframes (9 samples per segment; tasks loop back to the first keyframe) unless a pose is named. kg overrides in braces.', ''];
  const ex = (id, kg = {}) => (sex) => over(rec(id, kg, sex), sex);
  const T = (o, kg, start, action, style) => (sex) => over(task({ object: o, kg, start, action, style }, sex), sex, true);
  const cases = [
    ['barbell-curl', ex('barbell-curl')],
    ['seated-dumbbell-curl {"dbL":10,"dbR":10}', ex('seated-dumbbell-curl', { dbL: 10, dbR: 10 })],
    ['seated-dumbbell-curl leaned back (root pitch -10) {"dbL":10,"dbR":10}', (sex) => over(lean(rec('seated-dumbbell-curl', { dbL: 10, dbR: 10 }, sex)), sex)],
    ['task pick up bucket 10 kg, stoop', T('bucket', 10, 'floorFront', 'pick-up', 'stoop')],
    ['task pick up bucket 10 kg, squat', T('bucket', 10, 'floorFront', 'pick-up', 'squat')],
    ['task carry bag 10 kg, one hand', T('bag', 10, 'floorFront', 'carry', 'one-hand')],
    ['task carry bag 10 kg, split 5 + 5', T('bag', 10, 'floorFront', 'carry', 'both')],
    ['push-up', ex('push-up')],
    ['bench-press', ex('bench-press')],
    ['pull-up start (hang)', (sex) => at(rec('pull-up', {}, sex), 0, sex)],
    ['pull-up elbows bent', (sex) => at(rec('pull-up', {}, sex), 1, sex)],
    ['plank', ex('plank')],
  ];
  for (const [name, f] of cases) for (const sex of ['male', 'female']) { const r = f(sex); out.push(`### ${name} — ${sex}`, head(r), ...top(r), ''); }
  // R5 AC5 numbers: back-to-legs shift and the carry trunk change
  const lv = (r, plain, side) => Math.max(...data.parts.filter((p) => p.plain === plain && (!side || p.side === side)).map((p) => r.muscle[p.id]?.level ?? 0));
  out.push('## Acceptance numbers (AC5)', '');
  for (const sex of ['male', 'female']) {
    const [stoop, squat] = [cases[3], cases[4]].map(([, f]) => f(sex)), [one, both] = [cases[5], cases[6]].map(([, f]) => f(sex));
    out.push(`- ${sex} pick up 10 kg: lower back ${stoop.lowerBack.momentNm.toFixed(1)} Nm (stoop) -> ${squat.lowerBack.momentNm.toFixed(1)} Nm (squat)`);
    for (const m of ['Vastus lateralis muscle', 'Rectus femoris muscle']) out.push(`- ${sex} ${m}: ${lv(stoop, m).toFixed(2)} (stoop) -> ${lv(squat, m).toFixed(2)} (squat)`);
    for (const m of ['External abdominal oblique muscle', 'Quadratus lumborum muscle', 'Gluteus medius muscle']) out.push(`- ${sex} carry, left ${m}: ${lv(one, m, 'left').toFixed(2)} (10 kg one hand) -> ${lv(both, m, 'left').toFixed(2)} (5 + 5)`);
  }
  console.log(out.join('\n'));
}
await vite.close();
