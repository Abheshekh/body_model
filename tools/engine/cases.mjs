// Top 8 muscles per SPEC §4 case and sex, and engine timings. Loads the TS engine through Vite's SSR loader (no new deps).
// Usage: node tools/engine/cases.mjs [--time]    (cases to stdout; --time prints timing lines)
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';

const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const L = (p) => vite.ssrLoadModule(p);
const [{ fromPrototype }, { effort, effortOverMove, engineData }, { setupVariant }, { explain }] =
  await Promise.all([L('/src/rig/pose.ts'), L('/src/engine/effort.ts'), L('/src/engine/setup.ts'), L('/src/engine/explain.ts')]);

const read = (f) => JSON.parse(readFileSync(`public/data/${f}`, 'utf8'));
const data = engineData({ rig: read('body/rig.json'), manifest: read('body/manifest.json'), segments: read('segments.json'), strengths: read('strengths.json'), actions: read('actions.json') });
const tables = { loads: read('loads.json'), supports: read('supports.json') };
const all = [...read('exercises.json').exercises, ...read('tasks.json').tasks];

function variant(ex, id, kg, sex) {
  const v = all.find((x) => x.id === ex).variants.find((x) => x.id === id);
  return { v, a: fromPrototype(v.proto.a), b: fromPrototype(v.proto.b), input: { sex, ...setupVariant(ex, id, v.props, v.proto.a.pin, tables, kg) } };
}
const lean = (k) => fromPrototype({ ...k, root: { ...k.root, pitch: -10 } });
const PARTS = new Map(data.parts.map((p) => [p.id, p]));

function top(r) {
  const rows = Object.entries(r.muscle).filter(([, m]) => m.role !== 'none' && m.level > 0)
    .sort((x, y) => y[1].level - x[1].level || ['work', 'help', 'hold'].indexOf(x[1].role) - ['work', 'help', 'hold'].indexOf(y[1].role)).slice(0, 8);
  return rows.map(([id, m]) => { const p = PARTS.get(+id); return `- ${p.plain} (${p.side}) ${m.level.toFixed(2)} ${m.role} — ${m.reasons[0] ? explain(m.reasons[0], p.side) : ''}`; });
}
const head = (r) => `lowerBack ${r.lowerBack.momentNm.toFixed(1)} Nm (level ${r.lowerBack.level.toFixed(2)}); balance margin ${r.balance.margin.toFixed(3)} m${r.balance.comOverFeet ? '' : ' — The centre of mass is beyond the feet in this pose'}`;

if (process.argv.includes('--time')) {
  const med = (xs) => xs.sort((p, q) => p - q)[xs.length >> 1];
  for (const sex of ['male', 'female'])
    for (const [ex, id, kg] of [['curl', 'stand', {}], ['squat', 'back', {}], ['bucket', 'stoop', {}], ['pull', 'pullup', {}]]) {
      const { a, b, input } = variant(ex, id, kg, sex);
      for (let i = 0; i < 20; i++) { effort({ ...input, pose: a, poseB: b }, data); effortOverMove(a, b, input, data); } // warm-up
      const t1 = [], t9 = [];
      for (let i = 0; i < 200; i++) {
        let t = performance.now(); effort({ ...input, pose: a, poseB: b }, data); t1.push(performance.now() - t);
        t = performance.now(); effortOverMove(a, b, input, data); t9.push(performance.now() - t);
      }
      console.log(`${sex} ${ex}/${id}: effort ${med(t1).toFixed(2)} ms, effortOverMove(9) ${med(t9).toFixed(2)} ms`);
    }
} else {
  const out = ['# Cases: top 8 muscles per case and sex', '', 'Generated by tools/engine/cases.mjs. Levels 0..1; peak over a→b (9 samples) unless a pose is named. kg overrides in braces.', ''];
  const mv = (ex, id, kg, sex) => { const { a, b, input } = variant(ex, id, kg, sex); return effortOverMove(a, b, input, data); };
  const at = (ex, id, k, sex) => { const { a, b, input } = variant(ex, id, {}, sex); return effort({ ...input, pose: k === 'a' ? a : b, poseB: k === 'a' ? b : a }, data); };
  const cases = [
    ['curl/stand {}', (s) => mv('curl', 'stand', {}, s)],
    ['curl/seat {"dbL":10,"dbR":10}', (s) => mv('curl', 'seat', { dbL: 10, dbR: 10 }, s)],
    ['curl/seat leaned back (root pitch -10) {"dbL":10,"dbR":10}', (s) => { const { v, input } = variant('curl', 'seat', { dbL: 10, dbR: 10 }, s); return effortOverMove(lean(v.proto.a), lean(v.proto.b), input, data); }],
    ['bucket/stoop {}', (s) => mv('bucket', 'stoop', {}, s)],
    ['bucket/squat {}', (s) => mv('bucket', 'squat', {}, s)],
    ['carry/one {"bagR":10}', (s) => mv('carry', 'one', { bagR: 10 }, s)],
    ['carry/both {}', (s) => mv('carry', 'both', {}, s)],
    ['press/pushup {}', (s) => mv('press', 'pushup', {}, s)],
    ['press/bench {}', (s) => mv('press', 'bench', {}, s)],
    ['pull/pullup start (hang) {}', (s) => at('pull', 'pullup', 'a', s)],
    ['pull/pullup elbows bent {}', (s) => at('pull', 'pullup', 'b', s)],
    ['plank/front {}', (s) => mv('plank', 'front', {}, s)],
  ];
  for (const [name, f] of cases) for (const sex of ['male', 'female']) { const r = f(sex); out.push(`### ${name} — ${sex}`, head(r), ...top(r), ''); }
  console.log(out.join('\n'));
}
await vite.close();
